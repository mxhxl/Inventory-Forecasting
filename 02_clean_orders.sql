-- 1) Make a home for clean data
CREATE SCHEMA IF NOT EXISTS LOGISTICS_DB.CLEAN;

-- 2) KEEP LATEST: one row per order, newest file wins
CREATE OR REPLACE TABLE LOGISTICS_DB.CLEAN.LATEST_ORDERS AS
SELECT * FROM LOGISTICS_DB.RAW.RAW_ORDERS
QUALIFY ROW_NUMBER() OVER (PARTITION BY order_id ORDER BY source_file DESC) = 1;

-- 3) SPLIT, good rows: valid status, known customer, amount above 0
CREATE OR REPLACE TABLE LOGISTICS_DB.CLEAN.CLEAN_ORDERS AS
SELECT * FROM LOGISTICS_DB.CLEAN.LATEST_ORDERS
WHERE order_status IN ('PLACED','PACKED','SHIPPED','DELIVERED','CANCELLED')
  AND customer_id IN (SELECT customer_id FROM LOGISTICS_DB.RAW.RAW_CUSTOMERS)
  AND TRY_TO_NUMBER(order_amount) > 0;

-- 4) SPLIT, bad rows: everything that is not in the good table
CREATE OR REPLACE TABLE LOGISTICS_DB.CLEAN.REJECTED_ORDERS AS
SELECT * FROM LOGISTICS_DB.CLEAN.LATEST_ORDERS
WHERE order_id NOT IN (SELECT order_id FROM LOGISTICS_DB.CLEAN.CLEAN_ORDERS);

-- expected: good = 40, bad = 7
SELECT (SELECT COUNT(*) FROM LOGISTICS_DB.CLEAN.CLEAN_ORDERS)    AS good,
       (SELECT COUNT(*) FROM LOGISTICS_DB.CLEAN.REJECTED_ORDERS) AS bad;
